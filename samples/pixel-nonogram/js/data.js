// Build the run-length clue list for one line of cells (1 = filled).
function lineClue(cells) {
  const runs = [];
  let run = 0;
  for (const v of cells) {
    if (v) run++;
    else if (run) { runs.push(run); run = 0; }
  }
  if (run) runs.push(run);
  return runs.length ? runs : [0];
}
